import { readdir, mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const protectedDir = resolve(root, "src", "app", "(authenticated)");
const outFile = resolve(root, "src", "generated", "protected-routes.ts");

async function main() {
  const entries = await readdir(protectedDir, { withFileTypes: true });
  const routes = entries
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("("))
    .map((entry) => `/${entry.name}`)
    .sort();

  const content = [
    "// This file is auto-generated by scripts/generate-protected-routes.mjs.",
    "// Do not edit manually — it is derived from src/app/(authenticated)/.",
    "",
    `export const protectedRoutes = ${JSON.stringify(routes, null, 2)};`,
    "",
  ].join("\n");

  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, content);
  console.log(`Generated ${outFile} with ${routes.length} protected routes.`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
